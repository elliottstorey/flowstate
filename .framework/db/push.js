import migra from "@pgkit/migra";
import crypto from "crypto";
import fs from "fs/promises";
import { join } from "path";
import postgres from "postgres";

const rootDir = join(import.meta.dirname, "../../");
const dbUrl = process.env.DATABASE_URL;

if (!dbUrl) {
    console.error("❌ ERROR: DATABASE_URL is not set in the environment.");
    process.exit(1);
}

// --- 1. SCHEMA LOADER ---
// Flattens the complex logic into a clean, predictable file reader
async function loadCombinedSchema() {
    // Define paths in strict dependency order
    const basePaths = [
        ".framework/db/schema.sql",
        ".framework/auth/schema.sql",
        ".framework/payments/schema.sql",
        ".framework/ai/schema.sql",
        "schema.sql",
        "src/schema.sql"
    ].map((p) => join(rootDir, p));

    // Dynamically append any schemas located in src/schemas/
    try {
        const customDir = join(rootDir, "src/schemas");
        const files = await fs.readdir(customDir);
        basePaths.push(...files.filter((f) => f.endsWith(".sql")).sort().map((f) => join(customDir, f)));
    } catch {
        // Silently ignore if src/schemas directory does not exist
    }

    let combinedSql = "";
    for (const filePath of basePaths) {
        try {
            const content = await fs.readFile(filePath, "utf8");
            if (content.trim()) {
                combinedSql += `${content}\n\n`;
                console.log(`Loaded schema: ${filePath.replace(rootDir, "")}`);
            }
        } catch {
            // Silently skip files that do not exist yet
        }
    }

    if (!combinedSql.trim()) {
        throw new Error("No schema files were found. Please check your file paths.");
    }
    return combinedSql;
}

// --- 2. EXECUTE MIGRATION ---
const shadowDb = `shadow_${crypto.randomBytes(4).toString("hex")}`;
const shadowDbUrl = new URL(shadowDb, dbUrl).toString();

// Establish root connection (max 1 to prevent pool hanging, ignore background PG notices)
const sql = postgres(dbUrl, { max: 1, onnotice: () => {} });
let shadowSql;

try {
    console.log("Loading schema files...");
    const schema = await loadCombinedSchema();

    console.log(`Creating shadow database (${shadowDb})...`);
    await sql.unsafe(`CREATE DATABASE "${shadowDb}"`);

    // Connect specifically to the shadow DB
    shadowSql = postgres(shadowDbUrl, { max: 1, onnotice: () => {} });

    console.log("Initializing shadow schema...");
    await shadowSql.unsafe(schema);

    // Fetch user schemas in ALPHABETICAL ORDER to enforce dependency execution (auth before public)
    const schemas = await shadowSql`
        SELECT schema_name 
        FROM information_schema.schemata 
        WHERE schema_name NOT LIKE 'pg_%' AND schema_name != 'information_schema'
        ORDER BY schema_name ASC
    `;

    console.log("Diffing databases...");
    let appliedMigrations = false;

    for (const { schema_name } of schemas) {
        const diff = await migra.run(dbUrl, shadowDbUrl, {
            unsafe: true,
            schema: schema_name,
        });

        if (diff?.sql) {
            console.log(`Applying changes to schema: ${schema_name}`);
            
            // Patch specific escaping bug generated by Migra
            const patchedSql = diff.sql.replace(/'Author's Attitude'/g, "'Author''s Attitude'");
            await sql.unsafe(patchedSql);
            
            appliedMigrations = true;
        }
    }

    if (appliedMigrations) {
        console.log("\n✅ Schema migrations applied successfully!");
    } else {
        console.log("\n✅ Database is already up to date.");
    }

} catch (error) {
    console.error("\n❌ MIGRATION ERROR:");
    // Display the specific SQL syntax error cleanly without dumping a massive stack trace if possible
    console.error(error.message || error);
} finally {
    console.log("\nCleaning up...");
    // Always close and drop resources, even if a crash occurred midway through
    if (shadowSql) await shadowSql.end();
    await sql.unsafe(`DROP DATABASE IF EXISTS "${shadowDb}" WITH (FORCE)`);
    await sql.end();
}